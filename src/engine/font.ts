/** Width in pixels of `text` with 1px spacing. */
export function textWidth(text: string): number {
  return text.length * 4 - 1;
}

/** Call `plot(px, py)` for every lit pixel; py = 0 is the bottom row. */
export function rasterText(text: string, plot: (px: number, py: number) => void): void {
  let cx = 0;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    for (let row = 0; row < 5; row++)
      for (let col = 0; col < 3; col++) if (g[row][col] === '#') plot(cx + col, 4 - row);
    cx += 4;
  }
}
